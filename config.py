def stop_requested():
    """Стоп-кран. Проверяется перед каждым действием и внутри циклов."""
    return os.path.exists(STOP_FILE)


def set_stop(on=True):
    if on:
        with open(STOP_FILE, "w", encoding="utf-8") as f:
            f.write("остановлено вручную\n")
    elif os.path.exists(STOP_FILE):
        os.remove(STOP_FILE)
