def preset_for_key(key):
    """Чей это ключ — понять по нему самому.

    Сервисы метят ключи началом: OpenRouter выдаёт `sk-or-…`, DashScope —
    просто `sk-…`. Этого хватает, чтобы не заставлять человека выбирать
    сервис из списка: вставил ключ — адрес и модель подставились сами.
    Не угадали — выбор руками никуда не делся и важнее угадки.
    """
    key = (key or "").strip().lower()
    if key.startswith("sk-or-"):
        return "openrouter"
    return "qwen"


def preset_for_url(url):
    """Обратный ход: по адресу вспомнить сервис, чтобы взять его модель."""
    url = (url or "").strip().lower().rstrip("/")
    if not url:
        return ""
    for pid, (_, purl, _) in API_PRESETS.items():
        if purl and url.startswith(purl.lower().rstrip("/")):
            return pid
    return ""


def api_defaults(key="", url=""):
    """Адрес и модель, которыми заполняются пустые поля.

    Адрес важнее ключа: если человек уже вписал свой сервер, модель берём
    его, а не ту, что подошла бы по виду ключа.
    """
    pid = preset_for_url(url) or preset_for_key(key)
    _, purl, model = API_PRESETS.get(pid, API_PRESETS["qwen"])
    return purl, model
