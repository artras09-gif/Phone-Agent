def _find_adb():
    """Ищем adb.exe: переменная окружения -> PATH -> обычные места установки.

    Нужно потому, что после правки PATH переменная подхватывается только
    новыми процессами, а запустить агент хочется сразу.
    """
    import shutil

    def _exe(path):
        """Вернуть путь, только если это действительно исполняемый adb.

        Папку разворачиваем в adb.exe внутри неё: иначе CreateProcess падает
        с «WinError 193: не является приложением Win32» — по этой ошибке
        непонятно, что дело в пути.
        """
        if not path:
            return None
        if os.path.isdir(path):
            path = os.path.join(path, "adb.exe")
        if not os.path.isfile(path):
            path = shutil.which(path) or ""
        if path and os.path.splitext(path)[1].lower() in (".exe", ""):
            return path
        return None

    explicit = _exe(os.environ.get("ADB_PATH"))
    if explicit:
        return explicit

    found = _exe(shutil.which("adb"))
    if found:
        return found

    home = os.path.expanduser("~")
    near = os.path.dirname(BASE)   # переносимый комплект: tools рядом с проектом
    for path in (
        os.path.join(near, "tools", "platform-tools", "adb.exe"),
        os.path.join(BASE, "tools", "platform-tools", "adb.exe"),
        os.path.join(home, "tools", "platform-tools", "adb.exe"),
        os.path.join(home, "AppData", "Local", "Android", "Sdk", "platform-tools", "adb.exe"),
        r"C:\platform-tools\adb.exe",
    ):
        if os.path.exists(path):
            return path
    return "adb"


