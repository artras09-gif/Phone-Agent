"""Человекоподобное поведение.

Главное правило модуля: ни одной константы наружу. Всё, что видит телефон,
тянется из распределения. Ровные интервалы и одинаковые свайпы — первое,
по чему автоматизацию отличают от живого человека.
"""
import math
import random
import time

import abort
import adb
import config


def pause(lo, hi):
    """Пауза со смещением к нижней границе — так ведёт себя реакция человека.

    Спит через `abort.sleep`: почти все паузы агента идут отсюда, и кнопка
    «Остановить» должна срабатывать сразу, а не досиживать «отвлёкся на 40
    секунд» до конца.
    """
    t = random.triangular(lo, hi, lo + (hi - lo) * 0.3)
    abort.sleep(t)
    return t


def dwell():
    """Сколько смотрим одно видео.

    Логнормальное распределение: обычно 3-8 секунд, но изредка
    попадается длинный хвост — залип и досмотрел до конца.

    Хвост обрезан 20 секундами: короткие ролики зациклены, и сидеть на них
    полминуты — значит прокрутить один и тот же ролик несколько раз подряд.
    Живой человек так не делает, а со стороны выглядит зависшим ботом.
    """
    return min(max(random.lognormvariate(1.4, 0.85), 1.5), 20.0)


def chance(p):
    return random.random() < p


def deep_watch_gap(span=None, scale=1.0):
    """Через сколько роликов человек залипнет и досмотрит один целиком.

    Границы берутся из `config.DEEP_WATCH_EVERY`, но само число внутри них
    случайное на КАЖДЫЙ раз, а не «ровно каждый девятый». Постоянный шаг —
    это ровно тот признак, от которого весь модуль и избавляется: по журналу
    за час такая закономерность видна с одного взгляда.

    Ноль означает «не залипать»: так это выключается настройкой.
    """
    import config

    span = span or getattr(config, "DEEP_WATCH_EVERY", None)
    try:
        low, high = int(span[0]), int(span[1])
    except (TypeError, ValueError, IndexError):
        return 0
    if low <= 0 or high <= 0:
        return 0
    if high < low:
        low, high = high, low
    gap = random.randint(low, high)
    # Вечером залипается чаще, утром реже — поэтому промежуток делится на
    # множитель времени суток, а не умножается.
    if scale and scale > 0:
        gap = max(2, int(round(gap / scale)))
    return gap


def like_moment():
    """В какой доле просмотра человек жмёт «нравится». 0 — сразу, 1 — в конце.

    Раньше лайк ставился ВСЕГДА после того, как просмотр закончился, и за
    полсекунды-полторы до свайпа. То есть каждый лайк лежал в одной и той же
    точке относительно конца ролика — признак не менее заметный, чем ровный
    шаг свайпов, от которого избавлялись отдельно.

    Решений тут ДВА, а не одно, поэтому и распределение из двух частей.
    Обычно «нравится» приходит, когда человек уже посмотрел достаточно, —
    это поздняя часть. Но случается и мгновенное узнавание: свой автор,
    знакомый звук, — и лайк ставится почти сразу. Одной бетой такое не
    описать: при попытке смесь вырождается, и в первой пятой доле ролика
    оставалось 4% лайков вместо заметной доли.

    Бета не нуждается в обрезке: она задана на [0, 1], и бугра на краю,
    из-за которого заведён `draw`, здесь не возникает.
    """
    if random.random() < 0.22:              # узнал сразу
        return random.betavariate(1.3, 3.2)
    return random.betavariate(2.8, 1.7)     # решил, посмотрев


def daypart(when=None, amplitude=0.22, peak_hour=22.5):
    """Множитель «сколько сейчас смотрится» по времени суток.

    Поведение агента было одинаковым в девять утра и в одиннадцать вечера, а
    у человека это разные состояния: утром лента листается на бегу, вечером
    в неё залипают. Сессии и так расставлены по расписанию — не хватало
    того, чтобы они друг от друга ОТЛИЧАЛИСЬ.

    Кривая гладкая (один косинус за сутки), а не ступеньками по часам: любой
    скачок на границе часа — это ровно тот резкий признак, от которого
    избавляется весь модуль. Пик вечером, спад к позднему утру.

    Множитель постоянен на всю сессию: он про время суток, а не про
    настроение. За колебания внутри сессии отвечает `drift`.
    """
    when = when or time.localtime()
    hour = when.tm_hour + when.tm_min / 60.0
    return 1.0 + amplitude * math.cos(2 * math.pi * (hour - peak_hour) / 24.0)


def drift(mood, step=0.20, pull=0.10, lo=0.40, hi=2.5):
    """Следующее значение «настроения» сессии — медленное блуждание вокруг 1.

    Зачем. Все числа агента берутся заново на каждый ролик и не зависят от
    предыдущих. У живого человека внимание так себя не ведёт: идёт полоса
    быстрого пролистывания, потом медленная, потом опять. Отдельные значения
    при этом могут быть какими угодно правдоподобными — выдаёт именно
    ОТСУТСТВИЕ связи между соседними.

    Блуждание МУЛЬТИПЛИКАТИВНОЕ (шаг в логарифме), и размах у него больше,
    чем кажется нужным на глаз. Это не произвол, а следствие замера: время
    просмотра берётся из `dwell()`, логнормального с σ=0.85, и его
    собственный разброс огромен. Первая версия качала настроение на ±20% —
    связь соседних роликов выросла с 0.00 до 0.02, то есть настроения не
    было видно вообще за шумом самого dwell. Чтобы дрейф было ВИДНО в ряду,
    его разброс должен быть сопоставим с разбросом того, что он множит.

    `pull` возвращает к единице, иначе блуждание уходит к границе и там
    залипает: получилось бы не настроение, а плавно едущий множитель. При
    этих числах полоса держится порядка десятка роликов — примерно столько
    и длится «залип» или «листаю без интереса» у человека.

    Границы держим перевыбором шага, а не обрезкой, — по той же причине, по
    которой заведён `draw`: обрезка сажает хвост ровно на границу.

    Возврат идёт не к нулю логарифма, а чуть ниже. Это поправка, а не
    подкрутка: у мультипликативного блуждания среднее самого множителя равно
    exp(v/2) и всегда БОЛЬШЕ единицы, то есть простое `exp(блуждание)`
    удлинило бы все просмотры процентов на восемь. Дрейф должен менять
    ПОРЯДОК значений, а не их общий уровень: прежние замеры времени сессии
    остаются в силе.
    """
    # Установившийся разброс логарифма у этого блуждания; центр смещаем на
    # половину него вниз, тогда среднее множителя равно единице.
    spread = step * step / (1 - (1 - pull) ** 2)
    center = -0.5 * spread

    base = math.log(mood) if mood > 0 else 0.0
    for _ in range(24):
        value = math.exp(center + (1 - pull) * (base - center)
                         + random.gauss(0, step))
        if lo <= value <= hi:
            return value
    return 1.0


def draw(fn, lo, hi, tries=24):
    """Значение из распределения, попавшее в границы, — ПЕРЕВЫБОРОМ.

    Не `min(max(...))`. Обрезка сваливает весь хвост в одну точку, и та потом
    повторяется буквально: у прежней длины свайпа 18.7% значений садились
    ровно на верхнюю границу, у паузы между тапами 7.7% — ровно на нижнюю.
    То есть каждый пятый свайп был одной и той же длины, а это ровно тот
    признак, ради избавления от которого весь модуль и написан.

    Перевыбор сохраняет форму распределения внутри границ и не создаёт бугра
    на краю. Если за `tries` попыток не уложились (границы заданы слишком
    узко), берём равномерное — оно хотя бы не повторяется.
    """
    for _ in range(tries):
        value = fn()
        if lo <= value <= hi:
            return value
    return random.uniform(lo, hi)


def jitter_px(value, spread=0.04):
    """Сдвиг координаты на несколько процентов — палец не попадает в пиксель."""
    return value + random.uniform(-spread, spread) * value


def tap_point(node):
    """Точка внутри элемента: не центр, а случайное место в его середине."""
    x1, y1, x2, y2 = node.bounds
    cx = random.uniform(x1 + (x2 - x1) * 0.3, x1 + (x2 - x1) * 0.7)
    cy = random.uniform(y1 + (y2 - y1) * 0.3, y1 + (y2 - y1) * 0.7)
    return int(cx), int(cy)


def swipe_geometry(w, h, direction="up", quick=False):
    """Откуда, куда и за сколько. Вынесено отдельно, чтобы это можно было
    проверить статистикой, не трогая телефон.

    Три вещи, которых тут раньше не было:

    1. **Длительность считается из расстояния и скорости, а не сама по себе.**
       Раньше они выбирались независимо, и выпадал то вялый двухсотпиксельный
       перенос за 420 мс, то полтора экрана за 90 мс — 16 000 пикселей в
       секунду, чего пальцем не сделать. Теперь берётся скорость (у человека
       она логнормальна), а время получается делением.
    2. **Длина свайпа разная.** Было всегда «три четверти экрана вверх»; на
       деле человек то смахивает от души, то чуть подталкивает ленту.
    3. **Опасные полосы исключены.** Внизу под пальцем полоса перемотки и
       панель вкладок, справа — колонка кнопок (лайк, комментарии,
       «поделиться»). Начать жест там — это не свайп, а нажатие.
    """
    # Правый край отдан колонке кнопок, левый трогать можно, но человек редко
    # листает у самой рамки.
    x_start = random.uniform(w * 0.22, w * 0.72)

    # Правша ведёт палец не строго вертикально: сверху уводит к левому краю.
    # Величина сноса зависит от длины жеста, поэтому берём долей.
    drift = random.gauss(-0.03, 0.035) if random.random() < 0.75 \
        else random.gauss(0.03, 0.035)

    # Длина жеста: обычно пол-экрана, иногда короткий подталкивающий, изредка
    # размашистый во весь экран.
    span = draw(lambda: random.lognormvariate(-0.85, 0.42), 0.18, 0.62)

    # Полосы, где начинать жест нельзя.
    top, bottom = h * 0.14, h * 0.84
    if direction == "up":
        y_start = random.uniform(bottom - h * 0.10, bottom)
        y_end = max(top, y_start - h * span)
    else:
        y_start = random.uniform(top, top + h * 0.10)
        y_end = min(bottom, y_start + h * span)

    x_end = min(max(x_start + drift * w, w * 0.05), w * 0.95)

    # Скорость пальца, пикселей в секунду. Логнормальное: медиана около 3500
    # для обычного жеста и 5000 для «не зашло» — решение уже принято, и
    # смахивают резче. Числа подобраны так, чтобы granicы ниже почти НИКОГДА
    # не срабатывали: обрезанное распределение упирается в одно и то же
    # значение, и этот бугор на границе виден лучше, чем сама неровность.
    mu = 8.5 if quick else 8.15
    speed = draw(lambda: random.lognormvariate(mu, 0.38), 600.0, 12000.0)

    distance = math.hypot(x_end - x_start, y_end - y_start)
    # Время следует из расстояния и скорости; в границы оно упирается редко
    # (доли процента), потому что обе величины уже выбраны в разумных пределах.
    duration = int(min(max(distance / speed * 1000.0, 50), 900))
    return (x_start, y_start, x_end, y_end), duration, speed


def scroll_feed(w, h, direction="up", quick=False):
    """Свайп по ленте со случайной геометрией и скоростью.

    quick=True — короткая пауза после свайпа. Так листают неподходящий ролик:
    решение уже принято, ждать нечего. Обычная пауза остаётся для случаев,
    когда ролик досмотрели и человек ещё секунду думает.
    """
    (x1, y1, x2, y2), duration, _ = swipe_geometry(w, h, direction, quick)

    if config.SWIPE_ARC:
        _arc_swipe(x1, y1, x2, y2, duration)
    else:
        adb.swipe(x1, y1, x2, y2, duration)
    pause(0.05, 0.15) if quick else pause(0.4, 1.1)


def _arc_swipe(x1, y1, x2, y2, duration, points=12):
    """Жест дугой с разгоном и торможением — одной пачкой команд.

    `input swipe` рисует строго прямую линию с постоянной скоростью; палец так
    не ходит. Здесь путь выгнут, а точки расставлены неравномерно: густо в
    начале и в конце, редко в середине — это и есть разгон с торможением,
    потому что события уходят примерно через равные промежутки.

    Плата: 0.92 с против 0.41 у обычного свайпа (замерено на телефоне), и
    события идут реже, чем у настоящего тачскрина. Поэтому по умолчанию
    выключено — см. `config.SWIPE_ARC`.
    """
    side = random.choice((-1.0, 1.0))
    bow = random.uniform(0.02, 0.06) * side
    span = math.hypot(x2 - x1, y2 - y1)
    parts = []
    for i in range(points):
        t = i / (points - 1.0)
        ease = t * t * (3 - 2 * t)          # медленно - быстро - медленно
        x = x1 + (x2 - x1) * ease + bow * span * math.sin(math.pi * t)
        y = y1 + (y2 - y1) * ease
        parts.append((int(x), int(y)))

    cmd = "input motionevent DOWN %d %d" % parts[0]
    for p in parts[1:]:
        cmd += "; input motionevent MOVE %d %d" % p
    cmd += "; input motionevent UP %d %d" % parts[-1]
    adb.shell(cmd)


def scroll_comments(w, h):
    """Протяжка ВНУТРИ списка комментариев — не то же, что листание ленты.

    `scroll_feed` рассчитан на смену ролика: он длинный и быстрый, а тут
    нужно прокрутить список на несколько строк. Полосы у краёв те же самые
    опасные (снизу поле ввода «добавить комментарий», сверху шапка панели),
    поэтому работаем в середине.
    """
    x = draw(lambda: random.gauss(0.5, 0.1), 0.25, 0.75) * w
    y1 = draw(lambda: random.gauss(0.70, 0.05), 0.58, 0.80) * h
    length = draw(lambda: random.lognormvariate(-1.5, 0.45), 0.10, 0.38) * h
    speed = draw(lambda: random.lognormvariate(8.0, 0.35), 900, 6000)
    ms = max(60, int(length / speed * 1000))
    adb.swipe(jitter_px(x), y1, jitter_px(x), y1 - length, ms)
    return length / h, ms


def like_point(w, h):
    """Куда придётся двойной тап.

    Не «где-то в середине», а там, где у человека естественно оказывается
    большой палец: ниже центра и чуть в свою сторону. Правый край отдан
    колонке кнопок (лайк, комментарии, «поделиться»), низ — подписи и полосе
    перемотки; попасть туда двойным тапом значит открыть не то.
    """
    x = draw(lambda: random.gauss(0.47, 0.09), 0.18, 0.74)
    y = draw(lambda: random.gauss(0.52, 0.07), 0.30, 0.68)
    return w * x, h * y


def double_tap(x, y):
    """Лайк по двойному тапу — ОБА нажатия одной командой.

    **Так лайк вообще начал ставиться.** Раньше это были два отдельных вызова
    `adb.tap`, а каждый поход на телефон стоит своё время: между нажатиями
    выходило 258-286 мс вместо задуманных 140 (замерено). Android считает
    двойным нажатием то, что уложилось примерно в 300 мс, — то есть лайк жил
    на самой границе и срабатывал через раз. Проверено глазами: одиночным
    способом сердечко оставалось белым, пачкой — краснеет.

    Пауза исполняется НА ТЕЛЕФОНЕ (`sleep`), поэтому она и есть настоящая:
    время на дорогу в неё больше не входит.

    Два уточнения про то, как это выглядит со стороны системы:

    * **Промежуток** — около 140 мс с разбросом, перевыбором в границах
      (обрезка сваливала 7.7% значений ровно на 90 мс — один и тот же
      интервал у каждого двенадцатого лайка).
    * **Второй тап смещён на пиксели, а не на проценты.** Доля от координаты
      давала разброс тем больше, чем ниже по экрану (1% от y=1200 — это 12 px,
      а от y=300 — три); палец же промахивается одинаково, где бы ни касался.
    """
    # Промежуток около 105 мс. Верхнюю границу задаёт САМАЯ строгая сеть:
    # проверено глазами на живых роликах — Instagram Reels при 140 мс лайк
    # НЕ засчитывает (сердечко остаётся белым, первый тап лишь ставит паузу),
    # а при 90 мс краснеет. TikTok засчитывает и при 120. Поэтому держимся
    # заметно ниже 140, но не опускаемся к 50, где это уже похоже на дребезг
    # контакта, а не на палец.
    gap = draw(lambda: random.gauss(0.105, 0.022), 0.07, 0.155)
    x2 = int(x + random.gauss(0, 9))
    y2 = int(y + random.gauss(0, 11))
    adb.shell("input motionevent DOWN %d %d; input motionevent UP %d %d; "
              "sleep %.3f; "
              "input motionevent DOWN %d %d; input motionevent UP %d %d"
              % (int(x), int(y), int(x), int(y), gap, x2, y2, x2, y2))


def distracted():
    """Отвлёкся: телефон в руке, но человек смотрит в другую сторону."""
    return pause(10, 40)


def typing_delay():
    """Пауза перед вводом текста — человек сначала думает."""
    return pause(0.8, 2.5)
